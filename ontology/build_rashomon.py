# ---------- 検査（アクション型の「実行条件」にあたる） ----------
errs=[]; ids={}
for k in ('people','scenes','events','feelings','relations','devices','questions'):
    for o in D[k]:
        if o['id'] in ids: errs.append('ID重複 '+o['id'])
        ids[o['id']]=o
def chk(owner,e):
    if not (1<=e['par']<=len(P)): errs.append(f"{owner}: 段落番号が範囲外 {e['par']}")
    elif e['quote'] not in P[e['par']-1]: errs.append(f"{owner}: 引用が段落{e['par']}にない「{e['quote']}」")
n=0
for k in ('events','relations'):
    for o in D[k]: chk(o['id'],o['ev']); n+=1
for k in ('feelings','devices'):
    for o in D[k]:
        if not o['ev']: errs.append(o['id']+': 根拠がない')
        for e in o['ev']: chk(o['id'],e); n+=1
for o in questions: chk(o['id'],o['target']); n+=1
for o in feelings:
    for f in ('who','cause','scene'):
        if o[f] not in ids: errs.append(f"{o['id']}: {f} の参照先がない")
    if o['action'] and o['action'] not in ids: errs.append(o['id']+': action の参照先がない')
    s=ids[o['scene']]
    if not all(s['from']<=e['par']<=s['to'] for e in o['ev']): errs.append(o['id']+': 根拠が場面の範囲外')
    c=ids[o['cause']]
    if c['ev']['par']>o['ev'][0]['par']: errs.append(o['id']+': きっかけが心情より後に語られている')
for o in devices+questions:
    for x in o.get('links',[])+o.get('path',[]):
        if x not in ids: errs.append(f"{o['id']}: 参照先 {x} がない")
for o in questions:
    L=len(o['answer']); 
    if not 40<=L<=80: errs.append(f"{o['id']}: 解答例が{L}字")
cov=sorted({e['par'] for k in ('events','relations') for o in D[k] for e in [o['ev']]}|{e['par'] for k in ('feelings','devices') for o in D[k] for e in o['ev']})
print('引用の照合',n,'件 / エラー',len(errs)); [print(' ',e) for e in errs]
print('根拠のある段落',len(cov),'/',len(P)); print('解答例の字数',[len(q['answer']) for q in questions])
if errs: sys.exit(1)
json.dump(D,open('rashomon.json','w'),ensure_ascii=False,indent=1)
